-- 1. ΔΙΑΓΡΑΦΗ ΥΠΑΡΧΟΝΤΩΝ ΠΙΝΑΚΩΝ (se periptosi sfalmatos)
IF OBJECT_ID('MEASUREMENTS', 'U') IS NOT NULL DROP TABLE MEASUREMENTS;
IF OBJECT_ID('TEST_CYCLES', 'U') IS NOT NULL DROP TABLE TEST_CYCLES;
IF OBJECT_ID('BATTERIES', 'U') IS NOT NULL DROP TABLE BATTERIES;
GO

--1.BATTERY TABLE (GENERAL INFOS)
CREATE TABLE BATTERIES (
	Battery_ID NVARCHAR(50) PRIMARY KEY,
	Nominal_capacity FLOAT,
	Source_Dataset NVARCHAR(50)   -- ACKNOWLEDGE  NASA OR NATURE?
);

--2. TEST CYSCLES TABLE
CREATE TABLE TEST_CYCLES (
	Cycle_ID INT IDENTITY(1,1) PRIMARY KEY,
	Battery_ID NVARCHAR(50) FOREIGN KEY REFERENCES BATTERIES(Battery_ID),
	Cycle_Index INT,
	Operation_Type NVARCHAR(20), --charge or discharge
	Capacity_Ah FLOAT
);

--3. MEASUREMENTS TABLE (ALL SERIES)
CREATE TABLE MEASUREMENTS(
Measurement_ID BIGINT IDENTITY (1,1) PRIMARY KEY,
Cycle_ID INT FOREIGN KEY REFERENCES TEST_CYCLES(Cycle_ID),
Time_Seconds FLOAT,
Voltage_Measured FLOAT,
Current_Measured FLOAT,
Temperature_Measure FLOAT
);
